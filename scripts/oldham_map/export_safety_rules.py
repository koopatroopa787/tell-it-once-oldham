"""Export the deterministic safety rules in safety.py to frontend/data/safety-rules.js.

The front end applies them when it matches without the Pathly API, so the PII patterns and
crisis rules stay defined in one place. Run from the repo root after changing safety.py:

    python scripts/oldham_map/export_safety_rules.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import config  # noqa: E402
import safety  # noqa: E402

OUT = ROOT / "frontend" / "data" / "safety-rules.js"


def main() -> None:
    """Write the rules as a script that sets window.PATHLY_SAFETY."""
    pii = [[tag, p.pattern, "i" if p.flags & re.IGNORECASE else ""] for tag, p in safety.PII_PATTERNS]
    crisis = [
        {"label": label, "severity": severity, "patterns": patterns, "message": message}
        for label, severity, patterns, message in safety._CRISIS_RULES
    ]
    payload = {"borough": config.BOROUGH, "pii": pii, "crisis": crisis}
    OUT.write_text(
        "/* Generated by scripts/oldham_map/export_safety_rules.py from safety.py. Do not edit by hand. */\n"
        "window.PATHLY_SAFETY = " + json.dumps(payload, indent=1, ensure_ascii=False) + ";\n"
    )
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(pii)} PII patterns, {len(crisis)} crisis rules")


if __name__ == "__main__":
    main()
